package Loops;

public class Demo5 
{
   // for loop
	// Print 5 to 2 nos by using for loop__> 5 4 3 2
	public static void main(String[] args)
	{
          //    i=5  5>=2  i=4	
		   //        4>=2  i=3
		      //     3>=2  i=2
		          // 2>=2  i=1
		         //  1>=2
		for(int i=5; i>=2; i=i-1)
			{
			System.out.println(i);
			}
	}
}
